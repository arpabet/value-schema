package valueschema

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// TypeScript returns TypeScript declarations for definitions, one exported
// interface per definition name. The definitions of one name, its versions,
// are merged so that the interface reads a value of any of them: a field that
// every version has, required and of one type, is required; any other field
// is optional, and a field whose versions disagree takes the union of their
// types. An interface is named by the last element of the definition name,
// qualified by its package where two names share it.
//
// Field types are those @arpabet/vrpc reads: boolean; number for integers up
// to 32 bits and floats; number | bigint for 64-bit integers; bigint;
// number | VrpcDecimal for decimals (a number when it holds the decimal
// exactly); string; Uint8Array; Date; arrays; string-keyed objects; the
// interface of an object's definition, or an object of unknowns when it is
// not among the definitions; unknown for any; | null where nullable.
func TypeScript(types []Type) ([]byte, error) {
	byName := map[string][]Type{}
	for _, t := range types {
		if err := t.Validate(); err != nil {
			return nil, err
		}
		byName[t.Name] = append(byName[t.Name], t)
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)
	idents := tsIdents(names)

	g := tsGen{idents: idents}
	var body strings.Builder
	for _, name := range names {
		g.iface(&body, name, byName[name])
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Generated by go.arpabet.com/value-schema from %d definitions. Do not edit.\n", len(types))
	if g.decimal {
		out.WriteString("\nimport type { VrpcDecimal } from \"@arpabet/vrpc\";\n")
	}
	out.WriteString(body.String())
	return []byte(out.String()), nil
}

type tsGen struct {
	idents  map[string]string
	decimal bool
}

type tsField struct {
	types    []string
	versions int
	optional bool
}

func (g *tsGen) iface(out *strings.Builder, name string, versions []Type) {
	fields := map[string]*tsField{}
	var order []string
	for _, t := range versions {
		for _, f := range t.Fields {
			tf, ok := fields[f.Name]
			if !ok {
				tf = &tsField{}
				fields[f.Name] = tf
				order = append(order, f.Name)
			}
			tf.versions++
			tf.optional = tf.optional || f.Optional
			ts := g.tsType(f.Type)
			if !contains(tf.types, ts) {
				tf.types = append(tf.types, ts)
			}
		}
	}
	sort.Strings(order)
	fmt.Fprintf(out, "\n/** %s */\nexport interface %s {\n", name, g.idents[name])
	for _, fname := range order {
		tf := fields[fname]
		opt := ""
		if tf.optional || tf.versions < len(versions) {
			opt = "?"
		}
		fmt.Fprintf(out, "  %s%s: %s;\n", tsProperty(fname), opt, strings.Join(tf.types, " | "))
	}
	out.WriteString("}\n")
}

func (g *tsGen) tsType(ft FieldType) string {
	var s string
	switch ft.Kind {
	case KindBool:
		s = "boolean"
	case KindInt8, KindInt16, KindInt32, KindUint8, KindUint16, KindUint32, KindFloat32, KindFloat64:
		s = "number"
	case KindInt64, KindUint64:
		s = "number | bigint"
	case KindBigInt:
		s = "bigint"
	case KindDecimal:
		g.decimal = true
		s = "number | VrpcDecimal"
	case KindString:
		s = "string"
	case KindBytes:
		s = "Uint8Array"
	case KindTime:
		s = "Date"
	case KindList:
		elem := g.tsType(*ft.Elem)
		if strings.ContainsAny(elem, " |{") {
			s = "Array<" + elem + ">"
		} else {
			s = elem + "[]"
		}
	case KindMap:
		s = "{ [key: string]: " + g.tsType(*ft.Elem) + " }"
	case KindObject:
		if ident, ok := g.idents[ft.Object]; ok {
			s = ident
		} else {
			s = "{ [key: string]: unknown }"
		}
	default:
		s = "unknown"
	}
	if ft.Nullable && s != "unknown" {
		s += " | null"
	}
	return s
}

// tsIdents names the interfaces: the last element of each definition name,
// qualified by its package's last element where two names share it, and
// numbered where that is not enough.
func tsIdents(names []string) map[string]string {
	base := map[string]string{}
	count := map[string]int{}
	for _, n := range names {
		b := tsIdent(lastElem(n))
		base[n] = b
		count[b]++
	}
	out := map[string]string{}
	used := map[string]bool{}
	for _, n := range names {
		id := base[n]
		if count[id] > 1 {
			pkg := n[:max(0, strings.LastIndexByte(n, '.'))]
			if i := strings.LastIndexByte(pkg, '/'); i >= 0 {
				pkg = pkg[i+1:]
			}
			id = tsIdent(pkg) + id
		}
		for i := 2; used[id]; i++ {
			id = base[n] + strconv.Itoa(i)
		}
		used[id] = true
		out[n] = id
	}
	return out
}

// lastElem is what follows the last '.' outside brackets: the Go type name of
// a package path and name, type arguments included.
func lastElem(name string) string {
	depth := 0
	for i := len(name) - 1; i >= 0; i-- {
		switch name[i] {
		case ']':
			depth++
		case '[':
			depth--
		case '.':
			if depth == 0 {
				return name[i+1:]
			}
		}
	}
	return name
}

// tsIdent turns a name into a TypeScript identifier in PascalCase.
func tsIdent(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if r == '_' || r == '$' || unicode.IsLetter(r) || unicode.IsDigit(r) {
			if upper {
				r = unicode.ToUpper(r)
				upper = false
			}
			b.WriteRune(r)
		} else {
			upper = true
		}
	}
	id := b.String()
	if id == "" || unicode.IsDigit(rune(id[0])) {
		id = "T" + id
	}
	return id
}

// tsProperty is a property name, quoted unless it is an identifier.
func tsProperty(name string) string {
	for i, r := range name {
		if !(r == '_' || r == '$' || unicode.IsLetter(r) || (i > 0 && unicode.IsDigit(r))) {
			return strconv.Quote(name)
		}
	}
	if name == "" {
		return `""`
	}
	return name
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}
