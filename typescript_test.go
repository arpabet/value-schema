package valueschema_test

import (
	"reflect"
	"testing"

	vs "go.arpabet.com/value-schema"
)

func TestTypeScript(t *testing.T) {
	order, nested, err := vs.TypeOf(reflect.TypeOf(Item{}))
	if err != nil {
		t.Fatal(err)
	}
	str := vs.FieldType{Kind: vs.KindString}
	types := append([]vs.Type{order}, nested...)
	types = append(types,
		// Two versions of one name: "color" is in one only, "size" changed type.
		vs.Type{Name: "acme/shop.Product", Fields: []vs.Field{{Name: "id", Type: str}, {Name: "size", Type: vs.FieldType{Kind: vs.KindInt32}}}},
		vs.Type{Name: "acme/shop.Product", Fields: []vs.Field{{Name: "color", Type: str}, {Name: "id", Type: str}, {Name: "size", Type: str}}},
		// Two packages share a type name; field names that are not identifiers.
		vs.Type{Name: "acme/stock.Product", Fields: []vs.Field{
			{Name: "in-stock", Type: vs.FieldType{Kind: vs.KindBool}},
			{Name: "lots", Type: vs.FieldType{Kind: vs.KindList, Elem: &vs.FieldType{Kind: vs.KindInt64}}},
			{Name: "meta", Type: vs.FieldType{Kind: vs.KindMap, Elem: &vs.FieldType{Kind: vs.KindObject, Object: "elsewhere.Unknown", Nullable: true}}},
			{Name: "seen", Type: vs.FieldType{Kind: vs.KindTime}, Optional: true},
		}},
	)
	got, err := vs.TypeScript(types)
	if err != nil {
		t.Fatal(err)
	}
	want := `// Generated by go.arpabet.com/value-schema from 5 definitions. Do not edit.

import type { VrpcDecimal } from "@arpabet/vrpc";

/** acme/shop.Product */
export interface ShopProduct {
  color?: string;
  id: string;
  size: number | string;
}

/** acme/stock.Product */
export interface StockProduct {
  "in-stock": boolean;
  lots: Array<number | bigint>;
  meta: { [key: string]: { [key: string]: unknown } | null };
  seen?: Date;
}

/** go.arpabet.com/value-schema_test.Address */
export interface Address {
  city: string;
  zip?: string;
}

/** go.arpabet.com/value-schema_test.Item */
export interface Item {
  price: number | VrpcDecimal;
  qty: number | bigint;
  ship: Address | null;
  sku: string;
}
`
	if string(got) != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}
}
